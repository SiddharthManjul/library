use std::fmt::Write;

use library_core::Role;

use crate::methods::{Access, Link, METHODS, PUSHES, ScopeRule};

fn role_name(r: Role) -> &'static str {
    match r {
        Role::Member => "member",
        Role::DepartmentLead => "department lead",
        Role::ProductLeader => "product leader",
        Role::CSuite => "C-suite",
        Role::Admin => "admin",
    }
}

fn who(a: Access) -> String {
    match a {
        Access::Public => "no sign-in".into(),
        Access::Member => "any member".into(),
        Access::Server => "server only".into(),
        Access::Roles(rs) => rs
            .iter()
            .map(|r| role_name(*r))
            .collect::<Vec<_>>()
            .join(", "),
    }
}

/// `contracts/protocol.md`, generated from the method table. Never edit the file by hand.
pub fn render_protocol_md() -> String {
    let mut o = String::new();
    o.push_str("<!-- Generated by `cargo xtask contracts` from crates/protocol. Do not edit by hand. -->\n\n");
    o.push_str("# Protocol v1\n\nTwo links, both JSON-RPC 2.0. The desktop app talks to its local node over stdio (one JSON object per line). The node keeps one authenticated WebSocket to the gateway.\n\n");
    o.push_str("Every method declares who may call it, whether it names a scope the caller must hold, the lowest plan that may call it, and whether it writes. Writes carry an idempotency key; a replay returns the first result. The gateway rejects before the handler runs, and row-level security checks again in the database. Plan tiers are placeholders until pricing is set.\n");
    for (title, link) in [
        ("App to node", Link::AppToNode),
        ("Node to gateway", Link::NodeToGateway),
    ] {
        let _ = write!(
            o,
            "\n## {title}\n\n| Method | Who can call | Scope | Lowest plan | Writes | Purpose |\n| --- | --- | --- | --- | --- | --- |\n"
        );
        for m in METHODS.iter().filter(|m| m.link == link) {
            let scope = if m.scope == ScopeRule::Own {
                "caller must hold `scope_id`"
            } else {
                "-"
            };
            let _ = writeln!(
                o,
                "| `{}` | {} | {} | {:?} | {} | {} |",
                m.name,
                who(m.access),
                scope,
                m.plan,
                if m.write { "yes" } else { "no" },
                m.purpose
            );
        }
    }
    o.push_str("\n## Pushed notifications\n\n| Notification | Meaning |\n| --- | --- |\n");
    for p in PUSHES {
        let _ = writeln!(o, "| `{}` | {} |", p.name, p.purpose);
    }
    o.push_str("\n## Errors\n\nEvery error is `{ code, message, retryable }` inside the JSON-RPC error's `data`. Codes: `unauthenticated`, `token_expired`, `permission_denied`, `scope_denied`, `plan_required`, `rate_limited`, `payload_too_large`, `invalid_params`, `not_found`, `conflict`, `version_mismatch`, `approval_required`, `unavailable`, `internal`. Messages are safe to show a member and never contain SQL, paths or stack traces.\n\n");
    o.push_str(
        "## Not yet defined\n\n`jobs.claim` and `jobs.complete` (volunteer compute, after v0).\n",
    );
    o
}

/// `apps/desktop/src/generated/app-methods.ts`: the allowlist the Electron bridge enforces,
/// generated from the same table so the two can never drift apart.
pub fn render_app_methods_ts() -> String {
    let names = |link: Link| {
        METHODS
            .iter()
            .filter(|m| m.link == link)
            .map(|m| format!("  \"{}\",\n", m.name))
            .collect::<String>()
    };
    let pushes: String = PUSHES
        .iter()
        .map(|p| format!("  \"{}\",\n", p.name))
        .collect();
    format!(
        "// Generated by `cargo xtask contracts` from crates/protocol. Do not edit by hand.\n\n/** Methods the app may call on its local node. The Electron bridge refuses anything else. */\nexport const APP_METHODS = [\n{}] as const;\n\nexport type AppMethod = (typeof APP_METHODS)[number];\n\n/** Methods the node forwards to the gateway as `remote.<name>`. */\nexport const REMOTE_METHODS = [\n{}] as const;\n\n/** Notifications the node may push to the app. */\nexport const PUSH_EVENTS = [\n{}] as const;\n",
        names(Link::AppToNode),
        names(Link::NodeToGateway),
        pushes
    )
}
