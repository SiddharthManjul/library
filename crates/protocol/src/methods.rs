use library_core::{Plan, Role};

/// Which link a method travels on.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Link {
    /// Desktop app to its local node, over stdio.
    AppToNode,
    /// Local node to the gateway, over WSS.
    NodeToGateway,
}

/// Who may call.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Access {
    /// No credentials needed (the token itself is the credential).
    Public,
    /// Any signed-in member.
    Member,
    /// Only the listed roles.
    Roles(&'static [Role]),
    /// Server-internal: never callable from a node or the app.
    Server,
}

/// Whether the call names a scope the caller must hold.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ScopeRule {
    None,
    /// Params carry a `scope_id` the caller must hold right now.
    Own,
}

#[derive(Debug, Clone, Copy)]
pub struct MethodDecl {
    pub name: &'static str,
    pub link: Link,
    pub access: Access,
    pub scope: ScopeRule,
    /// Lowest plan that may call it.
    pub plan: Plan,
    /// Writes require an idempotency key.
    pub write: bool,
    pub purpose: &'static str,
}

#[derive(Debug, Clone, Copy)]
pub struct PushDecl {
    pub name: &'static str,
    pub purpose: &'static str,
}

const ADMIN: Access = Access::Roles(&[Role::Admin]);
const ADMIN_LEAD: Access = Access::Roles(&[Role::Admin, Role::DepartmentLead]);
const LEAD: Access = Access::Roles(&[Role::DepartmentLead]);
const LEADERS: Access = Access::Roles(&[Role::ProductLeader, Role::CSuite]);
const LEADERS_LEAD: Access =
    Access::Roles(&[Role::ProductLeader, Role::CSuite, Role::DepartmentLead]);
const APPROVERS: Access = Access::Roles(&[Role::DepartmentLead, Role::ProductLeader, Role::CSuite]);
const AUDITORS: Access = Access::Roles(&[Role::Admin, Role::CSuite]);

const fn m(
    name: &'static str,
    link: Link,
    access: Access,
    scope: ScopeRule,
    plan: Plan,
    write: bool,
    purpose: &'static str,
) -> MethodDecl {
    MethodDecl {
        name,
        link,
        access,
        scope,
        plan,
        write,
        purpose,
    }
}

